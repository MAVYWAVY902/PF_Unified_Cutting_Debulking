"""Generate a scalpel OBJ shaped like a No. 10 blade: a curved cutting edge (belly) rising to a point.

Axes as in generate_scalpel_obj.py / generate_scalpel_round_obj.py: X = blade length (heel at -X, tip at
+X), Y = depth (the cutting edge is the bottom, the back the top), Z = thickness. Same outer size and
wedge angle as scalpel_round.obj (L x D x T at the heel), so only the profile changes:

  - cutting edge  y_e(x) = -D/2 + (y_tip + D/2) u^2           u = (x + L/2) / L in [0, 1]
                  (flat at the heel, curving up to the tip: a convex belly);
  - back          y_b(x) =  D/2 - (D/2 - y_tip) u^4           (straight, curving down near the tip);
  - cross-section at every x: the same wedge as scalpel_round.obj (half-thickness s (y - y_e), s = T / (2 D))
    with a round back tangent to both faces at y_b; it shrinks to a point at the tip (u = 1).

Why: the extruded wedge had flat 60 mm end caps (x12). Drawn along its length - how a scalpel is used -
it led with a blunt plate and pushed tissue instead of cutting (40% of the tool path in a recorded cube
session). On the curved edge every segment except the flat heel bottom faces forward, so the edge leads
when the blade is drawn towards the tip (cut_curve: leading) and cuts.

The solid is the convex hull of the cross-sections (the profile is convex: y_e convex, y_b concave, and
the faces are linear in y - y_e), so it is convex (required by the exact CCD contact), watertight and
outward oriented. The cutting edge stays a sharp feature (wedge angle as before, < 30 deg).

Usage:
    python3 tools/generate_scalpel10_obj.py                       # resources/tools/scalpel10.obj (<= 256 triangles: exact CCD)
    python3 tools/generate_scalpel10_obj.py --sections 32 --segments 8
"""
import argparse
import math
from pathlib import Path

import numpy as np
from scipy.spatial import ConvexHull


def section(x, L, D, T, y_tip, segments):
    u = (x + L / 2.0) / L
    ye = -D / 2.0 + (y_tip + D / 2.0) * u * u
    yb = D / 2.0 - (D / 2.0 - y_tip) * u ** 4
    d = yb - ye
    if d <= 1e-12:
        return [(x, ye, 0.0)]
    s = 0.5 * T / D                             # side face: z = s (y - ye) (thickness T at depth D, as scalpel_round)
    k = math.sqrt(1.0 + s * s)
    c = d * k / (k + s)                         # round back centre (y relative to ye): s c / k = r, c + r = d
    r = d - c
    pts = [(x, ye, 0.0)]                        # cutting edge
    a0 = math.atan2(-s, 1.0)
    a1 = math.pi - a0
    for i in range(segments + 1):
        a = a0 + (a1 - a0) * i / segments
        pts.append((x, ye + c + r * math.sin(a), r * math.cos(a)))
    return pts


def generate(L, D, T, y_tip, n_sec, segments):
    pts = []
    for i in range(n_sec + 1):
        pts += section(-L / 2.0 + L * i / n_sec, L, D, T, y_tip, segments)
    P = np.array(pts)
    hull = ConvexHull(P)
    used = np.unique(hull.simplices)
    remap = {int(v): i for i, v in enumerate(used)}
    V = P[used]
    cen = V.mean(0)
    F = []
    for f in hull.simplices:
        a, b, c = (remap[int(v)] for v in f)
        n = np.cross(V[b] - V[a], V[c] - V[a])
        F.append((a, b, c) if np.dot(n, (V[a] + V[b] + V[c]) / 3.0 - cen) > 0 else (a, c, b))
    return V, F, hull.volume


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--length", type=float, default=0.012)
    ap.add_argument("--depth", type=float, default=0.005)
    ap.add_argument("--thickness", type=float, default=0.0008)
    ap.add_argument("--tip-height", type=float, default=0.2, help="tip height above the mid-line, fraction of depth")
    ap.add_argument("--sections", type=int, default=16, help="cross-sections along the length")
    ap.add_argument("--segments", type=int, default=4, help="arc segments of the round back")
    ap.add_argument("--output", default=str(Path(__file__).resolve().parents[1] / "resources/tools/scalpel10.obj"))
    a = ap.parse_args()
    V, F, vol = generate(a.length, a.depth, a.thickness, a.tip_height * a.depth, a.sections, a.segments)
    with open(a.output, "w") as fo:
        fo.write(f"# No. 10 scalpel profile (curved edge, pointed tip): L={a.length*1e3:.1f}mm D={a.depth*1e3:.1f}mm "
                 f"T={a.thickness*1e3:.2f}mm tip at {a.tip_height:.2f} D (generated by tools/generate_scalpel10_obj.py)\n")
        fo.write(f"# {len(V)} vertices, {len(F)} triangles\n")
        for v in V:
            fo.write(f"v {v[0]:.6f} {v[1]:.6f} {v[2]:.6f}\n")
        for f in F:
            fo.write(f"f {f[0]+1} {f[1]+1} {f[2]+1}\n")
    print(f"{a.output}: {len(V)} vertices, {len(F)} triangles, volume {vol*1e9:.3f} mm^3 "
          f"(extruded wedge {a.length*a.depth*a.thickness/2*1e9:.3f})")


if __name__ == "__main__":
    main()
