"""Generate a scalpel OBJ with a ROUNDED spine (same wedge and outer size as generate_scalpel_obj.py).

Geometry (axes as in generate_scalpel_obj.py: X = blade length, Y = depth, -Y = cutting edge,
Z = thickness):
  - the cross-section is the same wedge (sharp edge at y = -depth/2, thickness growing linearly to
    `thickness` at y = +depth/2), but its top is a circular arc tangent to both side faces and
    touching y = +depth/2: the flat spine is replaced by a round back;
  - extruded along X from -length/2 to +length/2, flat end caps.

Why: the flat spine (9.6 mm wide at the x12 scale used in the cube tests) pushed the tissue resting on
it straight up when the blade was pulled out, lifting it (strands / stuck knife). On a round back the
contact normals point sideways, so the tissue slides off to its own side, as on a real blade whose
back is a narrow rounded edge.

The solid stays convex (required by the exact CCD contact) and watertight with outward winding.
The cutting-edge wedge angle is unchanged (still a sharp feature for cut_features: auto).

Usage:
    python3 tools/generate_scalpel_round_obj.py                    # resources/tools/scalpel_round.obj
    python3 tools/generate_scalpel_round_obj.py --segments 24
"""
import argparse
import math
from pathlib import Path


def generate(length: float, depth: float, thickness: float, segments: int):
    L, D, T = length / 2.0, depth / 2.0, thickness / 2.0
    s = T / depth                                   # side face: z = s * (y + D)
    k = math.sqrt(1.0 + s * s)
    # circle centre (y = c, z = 0), radius r: tangent to the side faces, top at y = D
    #   s (c + D) / k = r,  c + r = D
    c = (D * k - s * D) / (k + s)
    r = D - c
    # cross-section polygon (z, y), counter-clockwise seen from +x
    poly = [(0.0, -D)]                               # cutting edge
    a0 = math.atan2(-s, 1.0)                         # arc from the +z tangent point (side normal (dz, dy) ~ (1, -s))
    a1 = math.pi - a0
    for i in range(segments + 1):
        a = a0 + (a1 - a0) * i / segments
        poly.append((r * math.cos(a), c + r * math.sin(a)))
    n = len(poly)
    verts = [(-L, y, z) for (z, y) in poly] + [(L, y, z) for (z, y) in poly]
    faces = []
    for i in range(n):
        j = (i + 1) % n
        a, b, cc, d = i, j, n + j, n + i             # quad on the side between polygon edge i -> j
        faces += [(a, b, cc), (a, cc, d)]
    for i in range(1, n - 1):                        # end caps (fans)
        faces.append((0, i + 1, i))                  # x = -L
        faces.append((n, n + i, n + i + 1))          # x = +L
    # orient every face outward (convex solid: away from the centroid)
    cx = [sum(v[q] for v in verts) / len(verts) for q in range(3)]
    out = []
    for f in faces:
        p = [verts[i] for i in f]
        e1 = [p[1][q] - p[0][q] for q in range(3)]
        e2 = [p[2][q] - p[0][q] for q in range(3)]
        nrm = [e1[1] * e2[2] - e1[2] * e2[1], e1[2] * e2[0] - e1[0] * e2[2], e1[0] * e2[1] - e1[1] * e2[0]]
        m = [(p[0][q] + p[1][q] + p[2][q]) / 3 - cx[q] for q in range(3)]
        out.append(f if sum(nrm[q] * m[q] for q in range(3)) > 0 else (f[0], f[2], f[1]))
    return verts, out, r, c


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--length", type=float, default=0.012)
    ap.add_argument("--depth", type=float, default=0.005)
    ap.add_argument("--thickness", type=float, default=0.0008)
    ap.add_argument("--segments", type=int, default=16, help="arc segments of the round back")
    ap.add_argument("--output", default=str(Path(__file__).resolve().parents[1] / "resources/tools/scalpel_round.obj"))
    a = ap.parse_args()
    verts, faces, r, c = generate(a.length, a.depth, a.thickness, a.segments)
    vol = 0.0
    for f in faces:
        p0, p1, p2 = (verts[i] for i in f)
        vol += (p0[0] * (p1[1] * p2[2] - p1[2] * p2[1]) - p0[1] * (p1[0] * p2[2] - p1[2] * p2[0])
                + p0[2] * (p1[0] * p2[1] - p1[1] * p2[0])) / 6.0
    with open(a.output, "w") as fo:
        fo.write(f"# Scalpel wedge with a round back: L={a.length*1e3:.1f}mm D={a.depth*1e3:.1f}mm "
                 f"T={a.thickness*1e3:.2f}mm, back radius {r*1e3:.3f}mm (generated by tools/generate_scalpel_round_obj.py)\n")
        fo.write(f"# {len(verts)} vertices, {len(faces)} triangles\n")
        for v in verts:
            fo.write(f"v {v[0]:.6f} {v[1]:.6f} {v[2]:.6f}\n")
        for f in faces:
            fo.write(f"f {f[0]+1} {f[1]+1} {f[2]+1}\n")
    print(f"{a.output}: {len(verts)} vertices, {len(faces)} triangles, back radius {r*1e3:.3f} mm "
          f"(centre y {c*1e3:.3f} mm), volume {vol*1e9:.3f} mm^3 (flat-back wedge "
          f"{a.length*a.depth*a.thickness/2*1e9:.3f})")


if __name__ == "__main__":
    main()
