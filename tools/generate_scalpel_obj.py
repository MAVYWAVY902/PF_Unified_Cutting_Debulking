"""Generate a minimal surgical scalpel OBJ for P(F) cutting demos.

Geometry: a triangular-prism wedge.
  - X axis = blade length (left-right along the cutting edge)
  - Y axis = blade depth (downward into tissue, -Y points into the cut)
  - Z axis = blade thickness (sharp at front, thick at back)

Cross-section (in YZ plane) is a triangle with vertices:
    A = (y=+depth/2, z=+thickness/2)   back-top
    B = (y=+depth/2, z=-thickness/2)   back-bottom
    C = (y=-depth/2, z=0)              sharp leading edge

Extruded along X from -length/2 to +length/2 → 6 vertices, 8 triangles.

Watertight + manifold + outward-winded so RigidMesh::compute_sdf produces a
correct SDF (sign via ray casting requires watertight).

Coordinates in METERS (consistent with rest of resources/* meshes).
Default dimensions match a small surgical scalpel:
    length=12mm, depth=5mm, thickness=0.8mm

Usage:
    python3 tools/generate_scalpel_obj.py
    python3 tools/generate_scalpel_obj.py --length 0.02 --depth 0.008 --thickness 0.001
    python3 tools/generate_scalpel_obj.py --output resources/tools/scalpel_large.obj
"""
import argparse
from pathlib import Path


def generate_scalpel(length: float, depth: float, thickness: float):
    """Return (vertices, faces) for a wedge scalpel.

    vertices: list of (x, y, z) tuples, in METERS.
    faces:    list of (i0, i1, i2) 1-indexed triangle vertex indices (OBJ convention),
              with CCW winding viewed from outside (outward normal via right-hand rule).
    """
    L = length / 2.0
    D = depth / 2.0
    T = thickness / 2.0

    # 6 vertices forming a triangular prism (wedge):
    #   v0,v1 = back-top edge   (z=+T, y=+D)
    #   v2,v3 = back-bottom edge (z=-T, y=+D)
    #   v4,v5 = sharp leading edge (z=0,  y=-D)
    vertices = [
        (-L, +D, +T),  # 0  back-top-left
        (+L, +D, +T),  # 1  back-top-right
        (-L, +D, -T),  # 2  back-bottom-left
        (+L, +D, -T),  # 3  back-bottom-right
        (-L, -D,  0),  # 4  sharp-edge-left
        (+L, -D,  0),  # 5  sharp-edge-right
    ]

    # 8 triangles (winding chosen so outward normals point away from body).
    # OBJ uses 1-indexed vertices, so we add 1 below when writing.
    faces = [
        # Back face (y = +D, normal = +Y)   — rectangle v0,v1,v3,v2 → 2 tris
        (0, 1, 3),
        (0, 3, 2),
        # Top-sloped face (back-top to sharp edge, normal points +Z-ish and -Y-ish)
        #   v0,v1 back-top → v5,v4 sharp edge
        (0, 4, 5),
        (0, 5, 1),
        # Bottom-sloped face (back-bottom to sharp edge, normal points -Z-ish and -Y-ish)
        #   v2,v3 back-bottom → v4,v5 sharp edge
        (2, 3, 5),
        (2, 5, 4),
        # Left endcap (triangle v0,v2,v4, normal = -X)
        (0, 2, 4),
        # Right endcap (triangle v1,v5,v3, normal = +X)
        (1, 5, 3),
    ]
    return vertices, faces


def write_obj(path: Path, vertices, faces, header_comment: str):
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w") as f:
        f.write(f"# {header_comment}\n")
        f.write(f"# {len(vertices)} vertices, {len(faces)} triangles\n")
        for v in vertices:
            f.write(f"v {v[0]:.6f} {v[1]:.6f} {v[2]:.6f}\n")
        for tri in faces:
            # OBJ is 1-indexed
            f.write(f"f {tri[0]+1} {tri[1]+1} {tri[2]+1}\n")


def main():
    ap = argparse.ArgumentParser(description="Generate minimal scalpel OBJ wedge.")
    ap.add_argument("--length", type=float, default=0.012,
                    help="Blade length along X (meters). Default 12mm.")
    ap.add_argument("--depth", type=float, default=0.005,
                    help="Blade depth along -Y (the part that enters tissue, meters). Default 5mm.")
    ap.add_argument("--thickness", type=float, default=0.0008,
                    help="Blade thickness at back along Z (meters). Default 0.8mm. "
                         "Front (sharp edge) is always 0.")
    ap.add_argument("--output", type=str,
                    default="resources/tools/scalpel.obj",
                    help="Output OBJ path (relative to repo root).")
    args = ap.parse_args()

    # Locate repo root (this script lives in tools/, repo is one level up).
    repo_root = Path(__file__).resolve().parent.parent
    out_path = repo_root / args.output

    vertices, faces = generate_scalpel(args.length, args.depth, args.thickness)
    header = (f"Scalpel wedge: L={args.length*1000:.1f}mm "
              f"D={args.depth*1000:.1f}mm T={args.thickness*1000:.2f}mm "
              f"(generated by tools/generate_scalpel_obj.py)")
    write_obj(out_path, vertices, faces, header)

    print(f"✓ Wrote {out_path}")
    print(f"  Blade dimensions: {args.length*1000:.1f}mm L × "
          f"{args.depth*1000:.1f}mm D × {args.thickness*1000:.2f}mm T")
    print(f"  Bbox: X=[{-args.length/2:.6f}, {args.length/2:.6f}]  "
          f"Y=[{-args.depth/2:.6f}, {args.depth/2:.6f}]  "
          f"Z=[{-args.thickness/2:.6f}, {args.thickness/2:.6f}]")
    print(f"  {len(vertices)} vertices, {len(faces)} triangles")
    print()
    # Sharp edge endpoints in local frame (the two vertices at y = -depth/2, z = 0)
    sharp_a = [-args.length/2, -args.depth/2, 0.0]
    sharp_b = [ args.length/2, -args.depth/2, 0.0]

    print("To use, add to your YAML config:")
    print(f"  knife:")
    print(f"    tool_mesh: \"../../{args.output}\"")
    print(f"    tool_sdf_resolution: 64")
    print(f"    # Sharp-edge damage (only this LINE cuts; blade body just pushes):")
    print(f"    sharp_edge_a: [{sharp_a[0]:.4f}, {sharp_a[1]:.4f}, {sharp_a[2]:.4f}]")
    print(f"    sharp_edge_b: [{sharp_b[0]:.4f}, {sharp_b[1]:.4f}, {sharp_b[2]:.4f}]")


if __name__ == "__main__":
    main()
